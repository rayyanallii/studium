const TOTAL = 25 * 60

function FocusDemo() {
  const [left, setLeft] = useState(TOTAL)
  const [running, setRunning] = useState(false)

  useEffect(() => {
    if (!running) return
    const id = window.setInterval(() => setLeft((value) => Math.max(0, value - 1)), 1000)
    return () => window.clearInterval(id)
  }, [running])

  useEffect(() => {
    if (left === 0) setRunning(false)
  }, [left])

  const pct = (left / TOTAL) * 100
  const minutes = Math.floor(left / 60)
  const seconds = String(left % 60).padStart(2, '0')

  return (
    <div className="bento-focus">
      <div className="bento-ring" style={{ ['--pct' as string]: `${pct}` }}>
        <div className="bento-ring-inner">
          <strong>
            {minutes}:{seconds}
          </strong>
          <small>{left === 0 ? 'Session done' : 'Focus session'}</small>
        </div>
      </div>
      <button type="button" className="bento-focus-btn" onClick={() => setRunning((value) => !value)} disabled={left === 0}>
        {running ? <Pause size={11} /> : <Play size={11} />}
        {running ? 'Pause' : left === TOTAL ? 'Start' : 'Resume'}
      </button>
    </div>
  )
}

