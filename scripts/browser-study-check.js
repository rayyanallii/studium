async (page) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/library')
  await page.getByRole('button', { name: 'Add material', exact: true }).click()
  await page.getByRole('tab', { name: 'Paste notes', exact: true }).click()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Verification upload notes')
  await page.getByRole('textbox', { name: 'Your notes', exact: true }).fill('Plants absorb light using chlorophyll in chloroplasts. Photosynthesis uses carbon dioxide and water to produce glucose and oxygen.')
  await page.getByRole('dialog').getByRole('button', { name: 'Add material', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  for (const extension of ['pdf', 'docx', 'png']) {
    await page.getByRole('button', { name: 'Add material', exact: true }).click()
    await page.getByRole('tab', { name: 'Upload a file', exact: true }).click()
    await page.getByLabel('Choose source file').setInputFiles(`output/study-check/biology.${extension}`)
    await page.getByRole('textbox', { name: 'Title', exact: true }).fill(`Verification upload ${extension}`)
    await page.getByRole('dialog').getByRole('button', { name: 'Add material', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden', timeout: 75000 })
    await page.getByText(`Verification upload ${extension}`, { exact: true }).first().waitFor()
  }
  await page.reload()
  for (const label of ['notes', 'pdf', 'docx', 'png']) await page.getByText(`Verification upload ${label}`, { exact: true }).first().waitFor()
  const response = await page.request.get('http://127.0.0.1:5173/api/study/artifacts')
  const artifacts = (await response.json()).data.items
  const deck = artifacts.find(item => item.kind === 'flashcards')
  const quiz = artifacts.find(item => item.kind === 'quiz')
  const notebook = artifacts.find(item => item.kind === 'notebook')
  await page.goto(`http://127.0.0.1:5173/study/${deck.id}`)
  await page.getByRole('button', { name: 'Reveal answer', exact: true }).click()
  await page.getByRole('button', { name: 'Got it', exact: true }).click()
  await page.getByRole('button', { name: 'Reveal answer', exact: true }).waitFor()
  await page.goto(`http://127.0.0.1:5173/study/${quiz.id}`)
  await page.getByRole('heading', { level: 1 }).waitFor()
  const groups = page.locator('fieldset')
  for (let index = 0; index < await groups.count(); index++) await groups.nth(index).getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Check my answers', exact: true }).click()
  await page.getByText('Your result', { exact: true }).waitFor()
  await page.goto(`http://127.0.0.1:5173/study/${notebook.id}`)
  await page.getByRole('textbox', { name: 'Ask your notebook', exact: true }).waitFor()
  await page.screenshot({ path: 'output/playwright/frosted-notebook.png', fullPage: true })
  await page.goto('http://127.0.0.1:5173/library')
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await page.screenshot({ path: 'output/playwright/frosted-library-light.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Study library overflows on mobile')
  await page.screenshot({ path: 'output/playwright/frosted-library-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('dialog', { name: 'More', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 1000 })
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('PASS: note/PDF/DOCX/image uploads, reload persistence, card review, quiz submission, notebook rendering, light theme and mobile navigation.')
}
