async (page) => {
  await page.goto('http://127.0.0.1:5173/library')
  await page.getByRole('heading', { level: 1 }).waitFor()
  const dark = page.getByRole('button', { name: 'Switch to dark theme' })
  if (await dark.count()) await dark.click()
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox', { name: 'Search pages and study sets' }).fill('Tasks')
  await page.getByRole('dialog').getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('heading', { name: 'Tasks', exact: true }).waitFor()
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  await page.getByRole('combobox', { name: 'Subject', exact: true }).click()
  await page.getByRole('option', { name: 'Mathematics', exact: true }).click()
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'combobox')
  await page.keyboard.press('Tab')
  await page.waitForFunction(() => !!document.activeElement?.closest('[role=dialog]'))
  await page.screenshot({ path: 'output/playwright/frosted-task-dialog.png' })
  await page.keyboard.press('Escape')
  await page.goto('http://127.0.0.1:5173/library')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await page.screenshot({ path: 'output/playwright/frosted-library-dark.png', fullPage: true })
  console.log('PASS: search navigation, select focus restoration and dialog styling.')
}
