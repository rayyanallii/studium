async (page) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('http://127.0.0.1:5173/tasks')
  await page.getByRole('button', { name: 'New task', exact: true }).waitFor({ state: 'visible' })
  await page.waitForLoadState('networkidle')
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  await page.screenshot({ path: 'output/playwright/spacing-final-mobile-dialog.png', animations: 'disabled' })
  const bounds = await dialog.boundingBox()
  if (bounds.y < 0 || bounds.y + bounds.height > 801) throw new Error('Dialog exceeds screen')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'output/playwright/spacing-final-mobile-dialog-footer.png', animations: 'disabled' })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:5173/dashboard')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await page.waitForLoadState('networkidle')
  await page.screenshot({ path: 'output/playwright/spacing-final-dashboard.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Settings', exact: true }).waitFor()
  await page.screenshot({ path: 'output/playwright/spacing-final-account-menu.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  return 'Mobile dialog fits, footer reachable, dashboard and account menu captured.'
}
