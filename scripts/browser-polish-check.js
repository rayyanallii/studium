async (page) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/tasks')
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New task', exact: true })
  await dialog.waitFor()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('UI verification task')
  await page.getByRole('combobox', { name: 'Subject', exact: true }).click()
  await page.getByRole('option', { name: 'Mathematics', exact: true }).click()
  for (let index = 0; index < 15; index++) {
    await page.keyboard.press('Tab')
    if (!await dialog.evaluate(element => element.contains(document.activeElement))) throw new Error('Dialog focus escaped')
  }
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.reload()
  await page.getByRole('button', { name: 'Actions for UI verification task', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Actions for UI verification task', exact: true }).click()
  console.log('Task creation, select interaction, focus containment, and refresh persistence passed.')
  await page.getByRole('menuitem', { name: 'Delete task', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Actions for UI verification task', exact: true }).waitFor({ state: 'hidden' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:5173/dashboard')
  await page.getByRole('heading', { level: 1 }).waitFor()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  if (overflow) throw new Error('Mobile dashboard overflows')
  await page.screenshot({ path: 'output/playwright/dashboard-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('dialog', { name: 'More', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'output/playwright/dashboard-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await page.screenshot({ path: 'output/playwright/dashboard-light.png', fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Switch to dark theme' }).waitFor()
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  console.log('Mobile overflow, navigation drawer, light/dark persistence passed. Runtime errors:', errors)
  if (errors.length) throw new Error(errors.join('\n'))
}
